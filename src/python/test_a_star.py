@pytest.mark.parametrize("case", CASES, ids=[c["name"] for c in CASES])
def test_given_cases(case):
    path = aStarAlgorithm(
        case["startRow"], case["startCol"], case["endRow"], case["endCol"], case["graph"]
    )
    check_path(case, path)


def test_unreachable_end_returns_empty_list():
    # The end cell is boxed in by walls.
    graph = [
        [0, 0, 0],
        [0, 1, 1],
        [0, 1, 0],
    ]
    assert aStarAlgorithm(0, 0, 2, 2, graph) == []


def test_straight_line_with_no_walls():
    graph = [[0] * 5]
    assert aStarAlgorithm(0, 0, 0, 4, graph) == [[0, 0], [0, 1], [0, 2], [0, 3], [0, 4]]


def test_does_not_modify_input_graph():
    case = CASES[0]
    original = [row[:] for row in case["graph"]]
    aStarAlgorithm(case["startRow"], case["startCol"], case["endRow"], case["endCol"], case["graph"])
    assert case["graph"] == original
