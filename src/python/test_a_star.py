# ---------------------------------------------------------------------------
# Reference shortest path length (plain breadth-first search)
# ---------------------------------------------------------------------------

def bfs_shortest_length(graph, start, end):
    """Number of cells on the shortest path (start and end included), or None."""
    rows, cols = len(graph), len(graph[0])
    queue = deque([(start, 1)])
    seen = {start}
    while queue:
        (r, c), length = queue.popleft()
        if (r, c) == end:
            return length
        for dr, dc in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nr, nc = r + dr, c + dc
            if 0 <= nr < rows and 0 <= nc < cols and graph[nr][nc] == 0 and (nr, nc) not in seen:
                seen.add((nr, nc))
                queue.append(((nr, nc), length + 1))
    return None


def check_path(case, path):
    graph = case["graph"]
    start = (case["startRow"], case["startCol"])
    end = (case["endRow"], case["endCol"])
    expected_length = bfs_shortest_length(graph, start, end)

    if expected_length is None:
        assert path == [], f"end is unreachable, expected [] but got {path}"
        return

    assert path, "expected a path but got an empty list"
    assert tuple(path[0]) == start, f"path starts at {path[0]}, expected {list(start)}"
    assert tuple(path[-1]) == end, f"path ends at {path[-1]}, expected {list(end)}"

    for r, c in path:
        assert graph[r][c] == 0, f"path goes through a wall at {[r, c]}"

    for (r1, c1), (r2, c2) in zip(path, path[1:]):
        assert abs(r1 - r2) + abs(c1 - c2) == 1, (
            f"step from {[r1, c1]} to {[r2, c2]} is not a single up/down/left/right move"
        )

    assert len(path) == expected_length, (
        f"path has {len(path)} cells but the shortest path has {expected_length}"
    )


